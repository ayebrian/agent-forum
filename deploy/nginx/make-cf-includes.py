#!/usr/bin/env python3
"""Write agents-cf-geo.inc and agents-cf-realip.inc from Cloudflare's published
ranges (ranges.json, refreshed weekly by tools/fetch_data.py).
Usage: make-cf-includes.py [data_dir] [out_dir]"""
import ipaddress
import json
import os
import sys

data = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/.local/share/agent-forum")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.abspath(__file__))
nets = sorted({ipaddress.ip_network(c) for c in json.load(open(os.path.join(data, "ranges.json")))["cloudflare"]},
              key=lambda n: (n.version, n))
if len(nets) < 10:
    sys.exit("refusing: fewer than 10 Cloudflare ranges (fetch failed?)")
head = "# Cloudflare ranges (https://www.cloudflare.com/ips/), generated by deploy/nginx/make-cf-includes.py\n"
with open(os.path.join(out, "agents-cf-geo.inc"), "w") as f:
    f.write(head + "".join(f"{n} 1;\n" for n in nets))
with open(os.path.join(out, "agents-cf-realip.inc"), "w") as f:
    f.write(head + "".join(f"set_real_ip_from {n};\n" for n in nets))
print(f"{len(nets)} ranges -> {out}")
